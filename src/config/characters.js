export function getCharacters() {
  return CHARACTERS;
}


export function getCharacterById(
  characterId,
) {
  if (
    typeof characterId !==
    'string'
  ) {
    return null;
  }


  return (
    CHARACTERS.find(
      (character) =>
        character.id ===
        characterId,
    ) ??
    null
  );
}


export function hasCharacter(
  characterId,
) {
  return (
    getCharacterById(
      characterId,
    ) !== null
  );
}