/*
 * Alle verfügbaren Skins eines Charakters.
 */

export function getCharacterSkins(
  characterId,
) {
  return Object.values(
    CHARACTER_SKINS,
  ).filter(
    (skin) =>
      skin.characterId ===
      characterId,
  );
}


/*
 * Einen konkreten Skin ermitteln.
 */

export function getCharacterSkinById(
  skinId,
) {
  if (
    typeof skinId !==
    'string'
  ) {
    return null;
  }

  return (
    CHARACTER_SKINS[
      skinId
    ] ??
    null
  );
}